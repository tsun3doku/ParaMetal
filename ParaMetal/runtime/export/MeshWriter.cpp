#include "MeshWriter.hpp"
#include "util/GeometryUtils.hpp"

#include <cmath>
#include <filesystem>
#include <fstream>
#include <glm/glm.hpp>
#include <iomanip>

static glm::vec3 transformPoint(const glm::vec3& p, const std::array<float, 16>* matrix) {
    if (!matrix) return p;
    const glm::mat4 mat = toMat4(*matrix);
    const glm::vec4 transformed = mat * glm::vec4(p, 1.0f);
    return glm::vec3(transformed.x, transformed.y, transformed.z);
}

static glm::vec3 transformNormal(const glm::vec3& n, const std::array<float, 16>* matrix) {
    if (!matrix) return n;
    const glm::mat4 mat = toMat4(*matrix);
    const glm::mat3 normalMat = glm::transpose(glm::inverse(glm::mat3(mat)));
    return safeNormalize(normalMat * n);
}

ExportResult MeshWriter::writeOBJ(
    const std::string& filePath,
    const std::vector<float>& positions,
    const std::vector<uint32_t>& triangleIndices,
    const std::vector<float>& normals,
    const std::array<float, 16>* localToWorld) {
    if (positions.empty() || triangleIndices.empty()) {
        return {false, "No mesh geometry to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        out << "# Wavefront OBJ mesh exported from ParaMetal\n";
        const size_t vertexCount = positions.size() / 3;
        out << "# Vertices: " << vertexCount << "\n";
        out << "# Triangles: " << (triangleIndices.size() / 3) << "\n\n";

        out << std::fixed << std::setprecision(6);
        for (size_t i = 0; i < vertexCount; ++i) {
            const glm::vec3 orig(positions[3 * i], positions[3 * i + 1], positions[3 * i + 2]);
            const glm::vec3 pos = transformPoint(orig, localToWorld);
            out << "v " << pos.x << " " << pos.y << " " << pos.z << "\n";
        }

        const bool hasNormals = !normals.empty() && (normals.size() / 3 == vertexCount);
        if (hasNormals) {
            for (size_t i = 0; i < vertexCount; ++i) {
                const glm::vec3 orig(normals[3 * i], normals[3 * i + 1], normals[3 * i + 2]);
                const glm::vec3 norm = transformNormal(orig, localToWorld);
                out << "vn " << norm.x << " " << norm.y << " " << norm.z << "\n";
            }
        }

        const size_t triangleCount = triangleIndices.size() / 3;
        for (size_t i = 0; i < triangleCount; ++i) {
            const uint32_t i0 = triangleIndices[3 * i + 0] + 1;
            const uint32_t i1 = triangleIndices[3 * i + 1] + 1;
            const uint32_t i2 = triangleIndices[3 * i + 2] + 1;
            if (hasNormals) {
                out << "f " << i0 << "//" << i0 << " " << i1 << "//" << i1 << " " << i2 << "//" << i2 << "\n";
            } else {
                out << "f " << i0 << " " << i1 << " " << i2 << "\n";
            }
        }

        return {true, "Successfully exported " + std::to_string(triangleCount) + " triangles to OBJ", triangleCount};
    } catch (const std::exception& e) {
        return {false, std::string("OBJ export failed: ") + e.what(), 0};
    }
}

ExportResult MeshWriter::writePLY(
    const std::string& filePath,
    const std::vector<float>& positions,
    const std::vector<uint32_t>& triangleIndices,
    const std::array<float, 16>* localToWorld) {
    if (positions.empty() || triangleIndices.empty()) {
        return {false, "No mesh geometry to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        const size_t vertexCount = positions.size() / 3;
        const size_t triangleCount = triangleIndices.size() / 3;

        out << "ply\n";
        out << "format ascii 1.0\n";
        out << "comment Generated by ParaMetal\n";
        out << "element vertex " << vertexCount << "\n";
        out << "property float x\n";
        out << "property float y\n";
        out << "property float z\n";
        out << "element face " << triangleCount << "\n";
        out << "property list uchar int vertex_indices\n";
        out << "end_header\n";

        out << std::fixed << std::setprecision(6);
        for (size_t i = 0; i < vertexCount; ++i) {
            const glm::vec3 orig(positions[3 * i], positions[3 * i + 1], positions[3 * i + 2]);
            const glm::vec3 pos = transformPoint(orig, localToWorld);
            out << pos.x << " " << pos.y << " " << pos.z << "\n";
        }

        for (size_t i = 0; i < triangleCount; ++i) {
            out << "3 " << triangleIndices[3 * i + 0] << " "
                << triangleIndices[3 * i + 1] << " "
                << triangleIndices[3 * i + 2] << "\n";
        }

        return {true, "Successfully exported " + std::to_string(triangleCount) + " triangles to PLY", triangleCount};
    } catch (const std::exception& e) {
        return {false, std::string("PLY export failed: ") + e.what(), 0};
    }
}

ExportResult MeshWriter::writeSTL(
    const std::string& filePath,
    const std::vector<float>& positions,
    const std::vector<uint32_t>& triangleIndices,
    const std::array<float, 16>* localToWorld) {
    if (positions.empty() || triangleIndices.empty()) {
        return {false, "No mesh geometry to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        out << "solid ParaMetalMesh\n";
        out << std::fixed << std::setprecision(6);

        const size_t triangleCount = triangleIndices.size() / 3;
        for (size_t i = 0; i < triangleCount; ++i) {
            const uint32_t idx0 = triangleIndices[3 * i + 0];
            const uint32_t idx1 = triangleIndices[3 * i + 1];
            const uint32_t idx2 = triangleIndices[3 * i + 2];

            const glm::vec3 v0 = transformPoint(glm::vec3(positions[3 * idx0], positions[3 * idx0 + 1], positions[3 * idx0 + 2]), localToWorld);
            const glm::vec3 v1 = transformPoint(glm::vec3(positions[3 * idx1], positions[3 * idx1 + 1], positions[3 * idx1 + 2]), localToWorld);
            const glm::vec3 v2 = transformPoint(glm::vec3(positions[3 * idx2], positions[3 * idx2 + 1], positions[3 * idx2 + 2]), localToWorld);

            const glm::vec3 edge1 = v1 - v0;
            const glm::vec3 edge2 = v2 - v0;
            const glm::vec3 normal = safeNormalize(glm::cross(edge1, edge2));

            out << "  facet normal " << normal.x << " " << normal.y << " " << normal.z << "\n";
            out << "    outer loop\n";
            out << "      vertex " << v0.x << " " << v0.y << " " << v0.z << "\n";
            out << "      vertex " << v1.x << " " << v1.y << " " << v1.z << "\n";
            out << "      vertex " << v2.x << " " << v2.y << " " << v2.z << "\n";
            out << "    endloop\n";
            out << "  endfacet\n";
        }

        out << "endsolid ParaMetalMesh\n";
        return {true, "Successfully exported " + std::to_string(triangleCount) + " triangles to STL", triangleCount};
    } catch (const std::exception& e) {
        return {false, std::string("STL export failed: ") + e.what(), 0};
    }
}
