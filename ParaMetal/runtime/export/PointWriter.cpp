#include "PointWriter.hpp"
#include "util/GeometryUtils.hpp"

#include <filesystem>
#include <fstream>
#include <glm/glm.hpp>
#include <iomanip>

static glm::vec3 transformPoint(const glm::vec3& p, const std::array<float, 16>* matrix) {
    if (!matrix) return p;
    const glm::mat4 mat = toMat4(*matrix);
    const glm::vec4 transformed = mat * glm::vec4(p, 1.0f);
    return glm::vec3(transformed.x, transformed.y, transformed.z);
}

ExportResult PointWriter::writeXYZ(
    const std::string& filePath,
    const std::vector<glm::vec4>& points,
    const std::array<float, 16>* localToWorld) {
    if (points.empty()) {
        return {false, "No points to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        out << std::fixed << std::setprecision(6);
        for (const glm::vec4& pt : points) {
            const glm::vec3 pos = transformPoint(glm::vec3(pt.x, pt.y, pt.z), localToWorld);
            out << pos.x << " " << pos.y << " " << pos.z << "\n";
        }

        return {true, "Successfully exported " + std::to_string(points.size()) + " points to XYZ", points.size()};
    } catch (const std::exception& e) {
        return {false, std::string("XYZ point export failed: ") + e.what(), 0};
    }
}

ExportResult PointWriter::writeCSV(
    const std::string& filePath,
    const std::vector<glm::vec4>& points,
    const std::array<float, 16>* localToWorld) {
    if (points.empty()) {
        return {false, "No points to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        out << "PointIndex,X,Y,Z\n";
        out << std::fixed << std::setprecision(6);
        for (size_t i = 0; i < points.size(); ++i) {
            const glm::vec3 pos = transformPoint(glm::vec3(points[i].x, points[i].y, points[i].z), localToWorld);
            out << i << "," << pos.x << "," << pos.y << "," << pos.z << "\n";
        }

        return {true, "Successfully exported " + std::to_string(points.size()) + " points to CSV", points.size()};
    } catch (const std::exception& e) {
        return {false, std::string("CSV point export failed: ") + e.what(), 0};
    }
}

ExportResult PointWriter::writePLY(
    const std::string& filePath,
    const std::vector<glm::vec4>& points,
    const std::array<float, 16>* localToWorld) {
    if (points.empty()) {
        return {false, "No points to export", 0};
    }

    try {
        const std::filesystem::path p(filePath);
        if (p.has_parent_path()) {
            std::filesystem::create_directories(p.parent_path());
        }

        std::ofstream out(filePath, std::ios::out | std::ios::trunc);
        if (!out.is_open()) {
            return {false, "Failed to open file for writing: " + filePath, 0};
        }

        out << "ply\n";
        out << "format ascii 1.0\n";
        out << "comment Generated by ParaMetal\n";
        out << "element vertex " << points.size() << "\n";
        out << "property float x\n";
        out << "property float y\n";
        out << "property float z\n";
        out << "end_header\n";

        out << std::fixed << std::setprecision(6);
        for (const glm::vec4& pt : points) {
            const glm::vec3 pos = transformPoint(glm::vec3(pt.x, pt.y, pt.z), localToWorld);
            out << pos.x << " " << pos.y << " " << pos.z << "\n";
        }

        return {true, "Successfully exported " + std::to_string(points.size()) + " points to PLY", points.size()};
    } catch (const std::exception& e) {
        return {false, std::string("PLY point export failed: ") + e.what(), 0};
    }
}

ExportResult PointWriter::writePoints(
    const std::string& filePath,
    ExportFormat format,
    const std::vector<float>& flatPositions,
    const std::array<float, 16>* localToWorld) {
    const size_t count = flatPositions.size() / 3;
    if (count == 0) {
        return {false, "No points to export", 0};
    }

    std::vector<glm::vec4> points;
    points.reserve(count);
    for (size_t i = 0; i < count; ++i) {
        points.emplace_back(flatPositions[3 * i], flatPositions[3 * i + 1], flatPositions[3 * i + 2], 1.0f);
    }

    if (format == ExportFormat::Auto) {
        format = exportutils::formatFromExtension(filePath);
    }

    if (format == ExportFormat::CSV) {
        return writeCSV(filePath, points, localToWorld);
    } else if (format == ExportFormat::PLY) {
        return writePLY(filePath, points, localToWorld);
    } else if (format == ExportFormat::XYZ) {
        return writeXYZ(filePath, points, localToWorld);
    } else {
        return {false, "Unsupported point cloud format: " + exportutils::exportFormatToString(format), 0};
    }
}
